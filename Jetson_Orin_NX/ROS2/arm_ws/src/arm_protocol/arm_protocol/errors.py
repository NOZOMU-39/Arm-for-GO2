def err_text(code: int, proto: str) -> str:
    """错误位 → 中文描述: 精确位优先，否则按位叠加（+），未知输出十六进制"""
    if not code:
        return "无错误 ✅"
    table = ERR_V3 if proto == "V3" else ERR_V44
    for bit, name in table:
        if bit == code:
            return name
    hits = [name for bit, name in table if (code & bit) == bit]
    if hits:
        return " + ".join(hits)
    return "未知错误位 " + format(code, "X").upper()
