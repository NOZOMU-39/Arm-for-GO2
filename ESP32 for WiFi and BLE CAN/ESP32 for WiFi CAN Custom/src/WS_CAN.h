#pragma once

/*============================================================================
 * WS_CAN.h — CAN 总线驱动 + 环形缓冲区
 *
 * 职责：
 *   1. TWAI (Two-Wire Automotive Interface) 驱动管理
 *   2. CAN 帧接收 → 写入环形缓冲区 (PSRAM)
 *   3. CAN 帧发送（支持自动分帧 >8 字节）
 *   4. 波特率在线切换 (25/50/100/125/250/500/800/1000 kbps)
 *   5. 收发速率统计（帧/秒）
 *   6. 自收回显过滤（避免自己的发送被当作接收统计）
 *
 * 环形缓冲区：
 *   CANTask 写入（生产者），TCP/Serial/Web 各自维护读指针（消费者）。
 *   消费者互不干扰，互斥锁只保护写操作。
 *============================================================================*/

#include "driver/twai.h"
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "freertos/semphr.h"
#include "WS_Config.h"

// ---- 环形缓冲区 (PSRAM) ----
extern CAN_Frame *can_ring;
extern volatile uint16_t can_ring_head;          // CANTask 写入位置
extern volatile uint16_t can_ring_tcp_tail;      // TCP 消费者读位置
extern volatile uint16_t can_ring_serial_tail;   // Serial 消费者读位置
extern volatile uint16_t can_ring_web_tail;      // Web 消费者读位置
extern SemaphoreHandle_t can_ring_mutex;          // 写互斥锁

// ---- CAN 状态 ----
extern uint32_t CAN_bitrate_kbps;
extern float    CAN_rx_rate;
extern float    CAN_tx_rate;
extern uint32_t CAN_rx_count;
extern uint32_t CAN_tx_count;

/*---------------------------------------------------------------------------
 * 初始化 TWAI 驱动 + 创建 CANTask
 *---------------------------------------------------------------------------*/
void CAN_Init(void);

/*---------------------------------------------------------------------------
 * 在线切换波特率 (kbps)
 *---------------------------------------------------------------------------*/
void CAN_UpdateRate(uint32_t bitrate_kbps);

/*---------------------------------------------------------------------------
 * 发送 CAN 帧（>8 字节自动分帧）
 *---------------------------------------------------------------------------*/
void CAN_Send(uint32_t CAN_ID, uint8_t *Data, uint8_t Data_length, bool Frame_type);

/*---------------------------------------------------------------------------
 * 发送 twai_message_t（内部模块用）
 *---------------------------------------------------------------------------*/
void CAN_SendMessage(twai_message_t message);

/*---------------------------------------------------------------------------
 * 查询某消费者有多少帧未读
 *---------------------------------------------------------------------------*/
uint16_t CAN_AvailableFrames(volatile uint16_t *tail);

/*---------------------------------------------------------------------------
 * 从环形缓冲区读取一帧（消费者调用）
 * 返回 true=读取成功, false=没有新帧
 *---------------------------------------------------------------------------*/
bool CAN_ReadFrame(volatile uint16_t *tail, CAN_Frame *out_frame);

/*---------------------------------------------------------------------------
 * 获取当前时间戳 (ms)，用于给 CAN 帧打时间
 *---------------------------------------------------------------------------*/
uint32_t CAN_GetTimestamp(void);

/*---------------------------------------------------------------------------
 * 帧协议：命令分发处理（TCP 和 Serial 共用）
 *---------------------------------------------------------------------------*/
void ProcessCommand(uint8_t *buf, uint16_t len);

/*---------------------------------------------------------------------------
 * CANTask 入口 (FreeRTOS)
 *---------------------------------------------------------------------------*/
void CANTask(void *parameter);
