#pragma once

/*============================================================================
 * WS_RTC.h — RTC 时钟（精简版）
 *
 * 保留 PCF85063 实时时钟芯片驱动，用于给 CAN 帧打时间戳。
 * 去掉定时事件引擎 (RTCTask / Continuous_Task / TimerEvent_*)。
 * RTC 时间按需读取，不再需要独立的 FreeRTOS 任务。
 *============================================================================*/

#include "WS_PCF85063.h"

/*---------------------------------------------------------------------------
 * 初始化 PCF85063 时钟芯片（无 FreeRTOS 任务）
 *---------------------------------------------------------------------------*/
void RTC_Init(void);

/*---------------------------------------------------------------------------
 * 获取当前日期时间字符串
 *   格式: "2024.12.20  14:30:05  Fri"
 *---------------------------------------------------------------------------*/
void RTC_GetTimeStr(char *buf, size_t buf_size);

/*---------------------------------------------------------------------------
 * 从 PCF85063 读取当前时间（更新全局 datetime 变量）
 *---------------------------------------------------------------------------*/
void RTC_Update(void);
